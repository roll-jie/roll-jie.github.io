import argparse
import re
from datetime import date
from html.parser import HTMLParser
from pathlib import Path

import markdown
import yaml
from jinja2 import Environment, FileSystemLoader
from markdown.extensions.toc import slugify_unicode


ROOT = Path(__file__).resolve().parents[1]
POST_NAME = re.compile(r"(\d{4}-\d{2}-\d{2})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md")
GENERATED = "<!-- Generated by scripts/build_blog.py. Edit _posts or the templates. -->"


class ParagraphExcerpt(HTMLParser):
    def __init__(self):
        super().__init__()
        self.in_paragraph = False
        self.finished = False
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag == "p" and not self.finished:
            self.in_paragraph = True
        if tag == "br" and self.in_paragraph:
            self.parts.append(" ")

    def handle_endtag(self, tag):
        if tag == "p" and self.in_paragraph:
            self.in_paragraph = False
            self.finished = True

    def handle_data(self, data):
        if self.in_paragraph:
            self.parts.append(data)


def read_post(path):
    match = POST_NAME.fullmatch(path.name)
    if not match:
        raise ValueError("use a filename like YYYY-MM-DD-my-post.md")
    published = date.fromisoformat(match[1]).isoformat()
    slug = match[2]
    if slug == "index":
        raise ValueError("'index' is reserved for the blog list")

    lines = path.read_text(encoding="utf-8-sig").splitlines()
    if not lines or lines[0] != "---" or "---" not in lines[1:]:
        raise ValueError("add YAML front matter between two --- lines")
    end = lines.index("---", 1)
    metadata = yaml.safe_load("\n".join(lines[1:end]))
    if not isinstance(metadata, dict):
        raise ValueError("front matter must contain a title")
    title = metadata.get("title")
    if not isinstance(title, str) or not title.strip():
        raise ValueError("title must be a non-empty string")
    tags = metadata.get("tags", [])
    if not isinstance(tags, list) or any(not isinstance(tag, str) or not tag.strip() for tag in tags):
        raise ValueError("tags must be a list of non-empty strings")
    description = metadata.get("description", "")
    if not isinstance(description, str):
        raise ValueError("description must be a string")

    body = markdown.markdown(
        "\n".join(lines[end + 1:]),
        extensions=["attr_list", "fenced_code", "tables", "toc"],
        extension_configs={"toc": {"slugify": slugify_unicode}},
    )
    excerpt = ParagraphExcerpt()
    excerpt.feed(body)
    excerpt.close()
    summary = " ".join("".join(excerpt.parts).split()) or description
    return {
        "slug": slug,
        "title": title.strip(),
        "published": published,
        "tags": [tag.strip() for tag in tags],
        "description": description or summary,
        "summary": summary,
        "body": body,
    }


def build_blog(output):
    posts = []
    slugs = set()
    for path in sorted((ROOT / "_posts").glob("*.md"), reverse=True):
        try:
            post = read_post(path)
            if post["slug"] in slugs:
                raise ValueError(f"duplicate URL: {post['slug']}.html")
        except (ValueError, yaml.YAMLError) as error:
            raise SystemExit(f"{path.name}: {error}") from error
        posts.append(post)
        slugs.add(post["slug"])

    templates = Environment(
        loader=FileSystemLoader(ROOT / "scripts" / "templates"),
        autoescape=True,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    index = templates.get_template("blog-index.html")
    article = templates.get_template("blog-post.html")
    pages = {"index.html": index.render(posts=posts, generated=GENERATED)}
    for post in posts:
        pages[f"{post['slug']}.html"] = article.render(post=post, generated=GENERATED)

    output.mkdir(parents=True, exist_ok=True)
    for name, html in pages.items():
        path = output / name
        if not path.exists() or path.read_text(encoding="utf-8") != html:
            path.write_text(html, encoding="utf-8")
    for path in output.glob("*.html"):
        if path.name not in pages and path.read_text(encoding="utf-8").startswith(f"<!doctype html>\n{GENERATED}"):
            path.unlink()

    print(f"Built {len(posts)} blog posts in {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build the static blog from Markdown posts.")
    parser.add_argument("--output", type=Path, default=ROOT / "blog")
    build_blog(parser.parse_args().output)
