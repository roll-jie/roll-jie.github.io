import argparse
import json
from pathlib import Path


SHOWCASE = Path(__file__).resolve().parents[1] / "showcase"
IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"}


def build_travel(showcase):
    photos_by_province = {}
    for folder in sorted((showcase / "photos").glob("*")):
        if not folder.is_dir() or folder.name.startswith("."):
            continue

        photos = [
            photo.name
            for photo in sorted(folder.iterdir())
            if photo.is_file()
            and not photo.name.startswith(".")
            and photo.suffix.lower() in IMAGE_EXTENSIONS
        ]
        if photos:
            photos_by_province[folder.name] = photos

    index = json.dumps(photos_by_province, ensure_ascii=False, indent=2)
    source = f"// Generated by scripts/build_travel.py from showcase/photos/.\nconst travelPhotosByProvince = {index};\n"
    output = showcase / "travel-photos.js"
    if not output.exists() or output.read_text(encoding="utf-8") != source:
        output.write_text(source, encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build the travel photo index from province folders.")
    parser.add_argument("--showcase", type=Path, default=SHOWCASE)
    build_travel(parser.parse_args().showcase)
